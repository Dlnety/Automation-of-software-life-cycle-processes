  CREATE OR REPLACE EDITIONABLE TRIGGER "STUDENT_APP"."TRG_GRADE_VALIDATE"
BEFORE INSERT OR UPDATE OF student_id, discipline_id, grade ON grades
FOR EACH ROW
DECLARE
    v_report_type curriculum.report_type%TYPE;
BEGIN
    SELECT c.report_type INTO v_report_type
    FROM students s
    JOIN study_groups g ON g.group_id = s.group_id
    JOIN curriculum c ON c.specialty_id = g.specialty_id AND c.discipline_id = :NEW.discipline_id
    WHERE s.student_id = :NEW.student_id
    FETCH FIRST 1 ROW ONLY;

    IF v_report_type = 'экзамен' AND :NEW.grade NOT IN ('2','3','4','5') THEN
        RAISE_APPLICATION_ERROR(-20020, 'Для экзамена допустимы оценки 2, 3, 4 или 5');
    ELSIF v_report_type = 'зачет' AND :NEW.grade NOT IN ('зачет','незачет') THEN
        RAISE_APPLICATION_ERROR(-20021, 'Для зачета допустимы значения зачет или незачет');
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20022, 'Для студента не найден учебный план по выбранной дисциплине');
END;
/
ALTER TRIGGER "STUDENT_APP"."TRG_GRADE_VALIDATE" ENABLE;


  CREATE OR REPLACE EDITIONABLE TRIGGER "STUDENT_APP"."TRG_STUDENTS_AUDIT"
AFTER INSERT OR UPDATE ON students
FOR EACH ROW
DECLARE
    v_operation audit_log.operation_type%TYPE;
    v_old_values audit_log.old_values%TYPE;
BEGIN
    IF INSERTING THEN
        v_operation := 'INSERT';
        v_old_values := NULL;
    ELSE
        v_operation := 'UPDATE';
        v_old_values :=
            'name=' || :OLD.last_name || ' ' || :OLD.first_name ||
            ';form=' || :OLD.study_form ||
            ';group=' || :OLD.group_id;
    END IF;

    INSERT INTO audit_log(
        operation_type,
        entity_name,
        record_id,
        username,
        old_values,
        new_values
    )
    VALUES(
        v_operation,
        'STUDENTS',
        TO_CHAR(:NEW.student_id),
        NVL(
            SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER'),
            SYS_CONTEXT('USERENV','SESSION_USER')
        ),
        v_old_values,
        'name=' || :NEW.last_name || ' ' || :NEW.first_name ||
        ';form=' || :NEW.study_form ||
        ';group=' || :NEW.group_id
    );
END;
/
ALTER TRIGGER "STUDENT_APP"."TRG_STUDENTS_AUDIT" ENABLE;

